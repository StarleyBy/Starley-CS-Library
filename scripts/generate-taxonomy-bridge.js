/**
 * Starley Medical Library - Taxonomy Bridge Generator
 * Computes live question counts per topic, discipline, and tag from quiz manifests,
 * and generates a compact summary for fast lookup in reader and search.
 */

const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');
const TAXONOMY_PATH = path.join(ROOT_DIR, 'quiz', 'quiz-taxonomy.json');
const QUIZ_DIR = path.join(ROOT_DIR, 'books', 'work', 'examen', 'quiz');
const OUTPUT_SUMMARY = path.join(ROOT_DIR, 'quiz', 'taxonomy-summary.json');
const CLIENT_BRIDGE_DATA = path.join(ROOT_DIR, 'assets', 'js', 'taxonomy-data.js');

function run() {
  console.log('🔄 Building Taxonomy Bridge and Topic Question Index...');

  if (!fs.existsSync(TAXONOMY_PATH)) {
    console.error(`❌ Taxonomy file not found: ${TAXONOMY_PATH}`);
    process.exit(1);
  }

  const taxonomy = JSON.parse(fs.readFileSync(TAXONOMY_PATH, 'utf8'));

  const topicCounts = {};
  const tagCounts = {};
  const disciplineCounts = {};
  let totalQuestionsWithTopics = 0;

  if (fs.existsSync(QUIZ_DIR)) {
    const files = fs.readdirSync(QUIZ_DIR).filter(f => f.endsWith('.json'));

    files.forEach(file => {
      const filePath = path.join(QUIZ_DIR, file);
      try {
        const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
        if (Array.isArray(data.questions)) {
          data.questions.forEach(q => {
            let hasTopic = false;
            if (Array.isArray(q.topics)) {
              q.topics.forEach(topId => {
                topicCounts[topId] = (topicCounts[topId] || 0) + 1;
                hasTopic = true;
              });
            }
            if (Array.isArray(q.tags)) {
              q.tags.forEach(tagId => {
                tagCounts[tagId] = (tagCounts[tagId] || 0) + 1;
              });
            }
            if (Array.isArray(q.disciplines)) {
              q.disciplines.forEach(discId => {
                disciplineCounts[discId] = (disciplineCounts[discId] || 0) + 1;
              });
            }
            if (hasTopic) totalQuestionsWithTopics++;
          });
        }
      } catch (err) {
        console.warn(`⚠️ Error reading quiz file ${file}:`, err.message);
      }
    });
  }

  const disciplineMap = {};
  (taxonomy.disciplines || []).forEach(d => {
    disciplineMap[d.id] = {
      id: d.id,
      nameRu: d.nameRu,
      nameEn: d.nameEn,
      icon: d.icon || '🩺',
      count: disciplineCounts[d.id] || 0
    };
  });

  const topicMap = {};
  (taxonomy.topics || []).forEach(t => {
    const parentDisc = disciplineMap[t.disciplineId] || {};
    topicMap[t.id] = {
      id: t.id,
      disciplineId: t.disciplineId,
      disciplineNameRu: parentDisc.nameRu || '',
      disciplineIcon: parentDisc.icon || '🫀',
      nameRu: t.nameRu,
      nameEn: t.nameEn,
      count: topicCounts[t.id] || 0
    };
  });

  // Build tag alias / lookup map
  const tagLookup = {};
  (taxonomy.tags || []).forEach(tg => {
    const count = tagCounts[tg.id] || 0;
    tagLookup[tg.id] = {
      id: tg.id,
      nameRu: tg.nameRu,
      nameEn: tg.nameEn,
      category: tg.category,
      topicIds: tg.topicIds || [],
      count
    };
  });

  // Read Book Taxonomy Map if exists
  let bookMap = {};
  const bookMapPath = path.join(ROOT_DIR, 'quiz', 'book-taxonomy-map.json');
  if (fs.existsSync(bookMapPath)) {
    try {
      bookMap = JSON.parse(fs.readFileSync(bookMapPath, 'utf8'));
    } catch (e) {
      console.warn('⚠️ Could not load book-taxonomy-map.json:', e.message);
    }
  }

  const summary = {
    meta: {
      generatedAt: new Date().toISOString(),
      totalDisciplines: (taxonomy.disciplines || []).length,
      totalTopics: (taxonomy.topics || []).length,
      totalTags: (taxonomy.tags || []).length,
      totalQuestionsIndexed: totalQuestionsWithTopics,
      totalCoreBooksMapped: Object.keys(bookMap).length
    },
    disciplines: disciplineMap,
    topics: topicMap,
    tags: tagLookup,
    bookMap: bookMap
  };

  fs.writeFileSync(OUTPUT_SUMMARY, JSON.stringify(summary, null, 2), 'utf8');
  console.log(`✅ Generated ${OUTPUT_SUMMARY} (${Object.keys(topicMap).length} topics, ${Object.keys(bookMap).length} core books)`);

  // Also write a lightweight client-side JS version for immediate browser execution
  const clientDataCode = `/**
 * Pre-compiled Taxonomy Bridge Data & Book Taxonomy Map
 * Auto-generated by scripts/generate-taxonomy-bridge.js
 */
window.STARLEY_TAXONOMY_SUMMARY = ${JSON.stringify(summary)};
window.STARLEY_BOOK_TAXONOMY_MAP = ${JSON.stringify(bookMap)};
`;
  fs.writeFileSync(CLIENT_BRIDGE_DATA, clientDataCode, 'utf8');
  console.log(`✅ Generated ${CLIENT_BRIDGE_DATA}`);
}

run();

